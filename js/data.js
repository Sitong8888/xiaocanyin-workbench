/* ---------- 行政区划查询 ---------- */
function getProvinces() { return CHINA.map(p => ({ id: p.id, name: p.name })); }
function getCities(provId) { const p = CHINA.find(x => x.id === provId); return p ? p.cities.map(c => ({ id: c.id, name: c.name })) : []; }
function getDistricts(provId, cityId) {
  const p = CHINA.find(x => x.id === provId); if (!p) return [];
  const c = p.cities.find(x => x.id === cityId);
  return c ? c.districts.map((d, i) => ({ id: 'd' + i, name: d })) : [];
}

/* ---------- 区域名解析 ---------- */
function regionNameOf(region) {
  if (!region) return '';
  if (region.dist) return region.dist;
  if (region.city) return region.city.name;
  if (region.prov) return region.prov.name;
  return '';
}
function shortName(n) {
  return (n || '').replace(/(省|市|自治区|特别行政区|壮族|回族|维吾尔|苗族|彝族|藏族|土家族|侗族|布依族|哈萨克|自治州|地区|县|区|盟|特区|新区|新区)$/g, '').slice(0, 4);
}

/* ---------- 区域动态洞察（确定性生成） ---------- */
function genRegionInsight(catId, l3Id, region) {
  if (!region || !region.prov) return null;
  const base = getAnalytics(catId, l3Id);
  if (!base) return null;
  const l3name = getNode(catId, l3Id) ? getNode(catId, l3Id).name : (l3Id || '');
  const rname = regionNameOf(region);
  const seed = catId + '|' + l3Id + '|' + (region.prov ? region.prov.id : '') + '|' + (region.city ? region.city.name : '') + '|' + (region.dist || '');
  const r = mulberry32(hashStr(seed));
  const rnd = (a, b) => a + (b - a) * r();
  const prov = REGION_PROFILE[region.prov.id] || REGION_PROFILE._DEFAULT;
  const sizeMod = prov.sizeMod;
  const baseHeat = heatToNum(prov.heat);
  const heat = Math.min(99, Math.max(18, Math.round(baseHeat + base.growth * 1.4 + rnd(-14, 14))));
  const competition = +Math.min(0.97, Math.max(0.18, base.competition + rnd(-0.16, 0.16))).toFixed(2);
  const ocean = heat >= 70 && competition < 0.6 ? 'blue'
              : heat >= 70 && competition >= 0.6 ? 'high'
              : heat < 45 && competition >= 0.7 ? 'red' : 'stable';
  // 本地 TOP 品牌（2 个本地新锐 + 1-2 个全国性连锁）
  const bn = BRAND_BANKS[catId] || BRAND_BANKS.catering;
  const suffix = LOCAL_SUFFIX[catId] || LOCAL_SUFFIX.catering;
  const sn = shortName(rname) || '本地';
  const localBrands = [];
  localBrands.push({ name: sn + pick(suffix, r), share: +rnd(8, 20).toFixed(1), local: true });
  localBrands.push({ name: sn + pick(suffix, r), share: +rnd(5, 14).toFixed(1), local: true });
  localBrands.push({ name: bn[Math.floor(r() * bn.length) % bn.length], share: +rnd(10, 26).toFixed(1), local: false });
  if (r() > 0.5) localBrands.push({ name: bn[Math.floor(r() * bn.length) % bn.length], share: +rnd(5, 14).toFixed(1), local: false });
  // 区域爆品卡（优先使用三级赛道预置爆品，缺省时回退品类词库）
  let products;
  if (base.hitProducts && base.hitProducts.length) {
    products = base.hitProducts.slice(0, 3).map(h => ({
      name: (rname.slice(0, 4) || '本地') + '·' + h.name,
      price: Math.max(1, Math.round(h.price * rnd(0.85, 1.15))),
      tag: h.tag || pick(['热销', '新品', '爆款'], r),
      heat: Math.round(rnd(62, 99)),
    }));
  } else {
    const pb = PRODUCT_BANK[catId] || PRODUCT_BANK.catering;
    products = [0, 1, 2].map(() => ({
      name: (rname.slice(0, 4) || '本地') + pick(pb, r),
      price: Math.max(1, Math.round(base.price * rnd(0.6, 1.4))),
      tag: pick(['热销', '新品', '引流', '爆款', '限时'], r),
      heat: Math.round(rnd(60, 99)),
    }));
  }
  // 本地化战略空位
  const s = base.strategy;
  const bank = CAT_BANKS[catId] || CAT_BANKS.catering;
  const gapType = s.gapType;
  const localGap = s.gap + `（落地「${rname}」时叠加本地标签：${prov.tags.slice(0, 2).join(' / ')}）`;
  const localPain = pick(bank.pain, r) + `（在${rname}表现为本地供给不足、选择少、信息不透明）`;
  const localWeak = `头部品牌在「${rname}」下沉不足 / 本地化弱，给新进入者留出了窗口`;
  const query = `${rname} ${l3name} 市场规模 竞品 痛点 战略空位 蓝海`;
  return { heat, competition, ocean, sizeMod, localBrands, products, gapType, localGap, localPain, localWeak, regionName: rname, query };
}

/* =========================================================================
 * 查询 / 辅助函数
 * ========================================================================= */
function getTree(catId) { return TREES[catId]; }
function getNode(catId, id) {
  const t = TREES[catId]; if (!t) return null;
  return t.L1[id] || t.L2[id] || t.L3[id] || null;
}
function getChildren(catId, parentId) {
  const t = TREES[catId]; if (!t) return [];
  if (parentId === null) return Object.values(t.L1);
  if (t.L1[parentId]) return Object.values(t.L2).filter(n => n.parentId === parentId);
  if (t.L2[parentId]) return Object.values(t.L3).filter(n => n.parentId === parentId);
  return [];
}
function getAnalytics(catId, id) { return (ANALYTICS[catId] && ANALYTICS[catId][id]) || null; }
function getPath(catId, l3Id) {
  const t = TREES[catId]; if (!t || !t.L3[l3Id]) return [];
  const node = t.L3[l3Id];
  const l2 = t.L2[node.parentId];
  const l1 = t.L1[l2.parentId];
  return [l1, l2, node];
}
function findL3Id(catId, name) {
  const t = TREES[catId]; if (!t) return null;
  return Object.keys(t.L3).find(id => t.L3[id].name === name) || null;
}
function getRegionProf(provId) { return REGION_PROFILE[provId] || REGION_PROFILE._DEFAULT; }

/* 区域定制：返回带区域系数调整的数据副本 */
function applyRegion(ana, provId) {
  if (!ana) return ana;
  if (!provId) return Object.assign({}, ana, { regionMod: 1, regionTags: [], regionHeat: '—' });
  const p = getRegionProf(provId);
  return Object.assign({}, ana, {
    marketSize: Math.round(ana.marketSize * p.sizeMod),
    trend: ana.trend.map(v => +(v * p.sizeMod).toFixed(1)),
    regionMod: p.sizeMod,
    regionTags: p.tags,
    regionHeat: p.heat,
  });
}

